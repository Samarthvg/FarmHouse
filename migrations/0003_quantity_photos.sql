-- Harvest quantities and bill photos.

-- When set, entries in this category also ask how much was sold (whole units).
ALTER TABLE categories ADD COLUMN unit TEXT CHECK (unit IS NULL OR unit IN ('kg', 'litre', 'box', 'crate'));
UPDATE categories SET unit = 'kg' WHERE id IN (20, 21, 22, 23, 24, 25);

ALTER TABLE entries ADD COLUMN quantity INTEGER CHECK (quantity IS NULL OR quantity > 0);

CREATE TABLE photos (
  id           TEXT    PRIMARY KEY, -- generated by the client so offline retries are idempotent
  entry_id     TEXT    NOT NULL REFERENCES entries (id),
  r2_key       TEXT    NOT NULL,
  content_type TEXT    NOT NULL,
  bytes        INTEGER NOT NULL,
  created_by   INTEGER REFERENCES users (id),
  created_at   INTEGER NOT NULL,
  deleted_at   INTEGER
);
CREATE INDEX photos_live_entry ON photos (entry_id) WHERE deleted_at IS NULL;

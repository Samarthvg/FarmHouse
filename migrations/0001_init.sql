-- Core schema. Money is stored in paise (integer) so sums are exact.

CREATE TABLE users (
  id              INTEGER PRIMARY KEY,
  name            TEXT    NOT NULL,
  role            TEXT    NOT NULL CHECK (role IN ('admin', 'manager')),
  pin_hash        TEXT    NOT NULL,
  lang            TEXT    NOT NULL DEFAULT 'hi' CHECK (lang IN ('hi', 'en')),
  active          INTEGER NOT NULL DEFAULT 1,
  failed_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until    INTEGER,
  created_at      INTEGER NOT NULL
);

CREATE TABLE sessions (
  token_hash TEXT    PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users (id),
  created_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL
);
CREATE INDEX sessions_user ON sessions (user_id);

CREATE TABLE categories (
  id             INTEGER PRIMARY KEY,
  kind           TEXT    NOT NULL CHECK (kind IN ('expense', 'income', 'capital')),
  name_en        TEXT    NOT NULL,
  name_hi        TEXT    NOT NULL,
  icon           TEXT    NOT NULL DEFAULT '',
  sort           INTEGER NOT NULL DEFAULT 100,
  -- Shown as a tile on the manager's entry screen. Admins always see every active category.
  show_on_entry  INTEGER NOT NULL DEFAULT 1,
  tracks_workers INTEGER NOT NULL DEFAULT 0,
  active         INTEGER NOT NULL DEFAULT 1,
  UNIQUE (kind, name_en)
);

CREATE TABLE entries (
  id                 TEXT    PRIMARY KEY, -- generated by the client so offline retries are idempotent
  kind               TEXT    NOT NULL CHECK (kind IN ('expense', 'income', 'capital')),
  category_id        INTEGER NOT NULL REFERENCES categories (id),
  entry_date         TEXT    NOT NULL, -- YYYY-MM-DD
  date_is_month_only INTEGER NOT NULL DEFAULT 0, -- imported rows only know the month
  amount_paise       INTEGER NOT NULL CHECK (amount_paise > 0),
  workers            INTEGER CHECK (workers IS NULL OR workers >= 0),
  note               TEXT    NOT NULL DEFAULT '',
  ref                TEXT,  -- legacy voucher number from the spreadsheet
  review_note        TEXT,  -- set when an entry needs the admin to look at it
  source             TEXT    NOT NULL DEFAULT 'app' CHECK (source IN ('app', 'import')),
  created_by         INTEGER REFERENCES users (id),
  created_at         INTEGER NOT NULL,
  updated_by         INTEGER REFERENCES users (id),
  updated_at         INTEGER NOT NULL,
  deleted_at         INTEGER
);
CREATE INDEX entries_live_date ON entries (entry_date, kind) WHERE deleted_at IS NULL;
CREATE INDEX entries_live_category ON entries (category_id, entry_date) WHERE deleted_at IS NULL;
CREATE INDEX entries_created ON entries (created_by, created_at);
CREATE INDEX entries_review ON entries (review_note) WHERE review_note IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE audit_log (
  id          INTEGER PRIMARY KEY,
  entry_id    TEXT    NOT NULL,
  user_id     INTEGER REFERENCES users (id),
  action      TEXT    NOT NULL CHECK (action IN ('create', 'update', 'delete', 'restore')),
  before_json TEXT,
  after_json  TEXT,
  at          INTEGER NOT NULL
);
CREATE INDEX audit_at ON audit_log (at);
CREATE INDEX audit_entry ON audit_log (entry_id, at);
